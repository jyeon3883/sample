import { promises as fs } from "node:fs";
import path from "node:path";

const START_MARKER = "// <auto-generated-endpoint-exports:start>";
const END_MARKER = "// <auto-generated-endpoint-exports:end>";

const projectRoot = path.resolve(".");
const indexPath = path.join(projectRoot, "src", "index.ts");
const generatedRoot = path.join(projectRoot, "src", "generated");

const toPosixPath = (value) => value.replaceAll("\\", "/");

async function readDirEntries(targetPath) {
  try {
    return await fs.readdir(targetPath, { withFileTypes: true });
  } catch {
    return [];
  }
}

async function collectEndpointFiles(dirPath) {
  const entries = await readDirEntries(dirPath);
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectEndpointFiles(fullPath)));
      continue;
    }
    if (!entry.isFile() || !entry.name.endsWith(".ts")) {
      continue;
    }
    if (entry.name.endsWith(".d.ts") || entry.name === "index.ts") {
      continue;
    }
    files.push(fullPath);
  }

  return files;
}

async function getServiceEndpointRoots() {
  const entries = await readDirEntries(generatedRoot);
  const roots = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }

    const endpointsRoot = path.join(generatedRoot, entry.name, "endpoints");
    try {
      await fs.access(endpointsRoot);
      roots.push(endpointsRoot);
    } catch {
      // skip non-orval service directories
    }
  }

  return roots.sort((a, b) => a.localeCompare(b));
}

function buildExportLines(filePaths) {
  const lines = filePaths
    .map((filePath) => {
      const relativePath = path.relative(path.join(projectRoot, "src"), filePath);
      const withoutExt = relativePath.replace(/\.ts$/, "");
      return `export * from "./${toPosixPath(withoutExt)}";`;
    })
    .sort((a, b) => a.localeCompare(b));

  return lines;
}

function replaceSection(content, replacementLines) {
  const startIndex = content.indexOf(START_MARKER);
  const endIndex = content.indexOf(END_MARKER);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    throw new Error("Auto-generated endpoint export markers were not found in src/index.ts");
  }

  const before = content.slice(0, startIndex + START_MARKER.length);
  const after = content.slice(endIndex);
  const middle = replacementLines.length ? `\n${replacementLines.join("\n")}\n` : "\n";
  return `${before}${middle}${after}`;
}

async function run() {
  const endpointRoots = await getServiceEndpointRoots();
  const endpointFiles = (
    await Promise.all(endpointRoots.map((root) => collectEndpointFiles(root)))
  ).flat();
  const exportLines = buildExportLines(endpointFiles);
  const indexContent = await fs.readFile(indexPath, "utf8");
  const nextContent = replaceSection(indexContent, exportLines);

  if (nextContent !== indexContent) {
    await fs.writeFile(indexPath, nextContent, "utf8");
  }

  console.log(`[sync-endpoint-exports] synced ${exportLines.length} endpoint exports`);
}

run().catch((error) => {
  const message = error instanceof Error ? error.stack ?? error.message : String(error);
  console.error(`[sync-endpoint-exports] ${toPosixPath(message)}`);
  process.exit(1);
});
